"""The Skaling law (arXiv:2608.07222), available beside the paper's laws but not among them.

Three things are pinned here:
  1. k == 1 is Chinchilla to floating-point equality (what makes a comparison with
     Chinchilla controlled).
  2. fit_skaling recovers planted parameters from data generated by the law, including
     an outer exponent above the old ceiling of 2.
  3. Skaling is in EXTRA_LAWS and not in LAWS, so the paper's tables and figures, which
     iterate over LAWS, are unchanged.
"""

from __future__ import annotations

import numpy as np
import pytest

from scaling_laws.laws import (
    EXTRA_LAWS,
    LAWS,
    chinchilla_loss,
    fit_skaling,
    skaling_loss,
)


# ════════════════════════════════════════════════════════════════
# 1. k = 1 reduces to Chinchilla exactly
# ════════════════════════════════════════════════════════════════

@pytest.mark.parametrize(
    "A, alpha, B, beta, E",
    [
        (4.1e2, 0.34, 4.1e3, 0.28, 1.69),
        (1.0, 0.5, 1.0, 0.5, 0.0),
        (9.87e5, 0.07, 3.21e1, 1.45, 2.5),
    ],
)
def test_skaling_at_k1_is_chinchilla(A, alpha, B, beta, E):
    """skaling_loss(..., k=1, ...) equals chinchilla_loss(...) in floating point.

    Exact to within one ulp, and NOT bitwise: both evaluate the same three
    summands, but chinchilla_loss associates them as (E + A/N^α) + B/D^β while
    this law must form the inner sum first to raise it to k, giving
    (A/N^α + B/D^β) + E. Float addition is commutative but not associative, so
    the two orders can differ in the last bit - the tolerance below is one
    relative ulp, not a fudge factor.
    """
    N = np.array([1e6, 2.5e7, 3e8, 1.1e9])
    D = np.array([2e7, 1e9, 4.5e9, 9e10])

    sk = skaling_loss(N, D, A, alpha, B, beta, 1.0, E)
    ch = chinchilla_loss(N, D, E, A, alpha, B, beta)

    np.testing.assert_allclose(sk, ch, rtol=np.finfo(float).eps, atol=0.0)

    # And bitwise once the association is matched: k=1 leaves the sum untouched.
    inner = A / N ** alpha + B / D ** beta
    assert np.array_equal(sk, inner + E)


def test_skaling_k_not_one_departs_from_chinchilla():
    """The k != 1 branch is not silently collapsing to the additive law."""
    N = np.array([1e6, 3e8])
    D = np.array([2e7, 4.5e9])
    ch = chinchilla_loss(N, D, 1.69, 4.1e2, 0.34, 4.1e3, 0.28)
    sk = skaling_loss(N, D, 4.1e2, 0.34, 4.1e3, 0.28, 0.8, 1.69)
    assert np.all(np.abs(sk - ch) > 1e-6)


def test_skaling_mixed_derivative_sign_follows_k():
    """d2L/dNdD has the sign of k(k-1): zero at k=1, negative for 0<k<1."""
    A, alpha, B, beta, E = 4.1e2, 0.34, 4.1e3, 0.28, 1.69
    N, D, h = 3e8, 4.5e9, 1e5

    def mixed(k):
        f = lambda n, d: skaling_loss(n, d, A, alpha, B, beta, k, E)
        return (f(N + h, D + h) - f(N + h, D - h)
                - f(N - h, D + h) + f(N - h, D - h)) / (4 * h * h)

    assert abs(mixed(1.0)) < 1e-30          # additive: identically zero
    assert mixed(0.7) < 0.0                 # k(k-1) < 0 for 0 < k < 1
    assert mixed(1.4) > 0.0                 # k(k-1) > 0 for k > 1


# ════════════════════════════════════════════════════════════════
# 2. The fitter recovers planted parameters
# ════════════════════════════════════════════════════════════════

def test_fit_skaling_recovers_planted_params():
    """Noise-free data generated from the law is recovered by fit_skaling.

    The planted surface is generated independently of the optimiser (an
    explicit formula written out here, not a call back into the fitter's own
    objective), so agreement is evidence and not a tautology.
    """
    A, alpha, B, beta, k, E = 5.0e3, 0.35, 8.0e4, 0.30, 0.85, 1.20

    n_grid = np.logspace(7, 9, 5)
    d_grid = np.logspace(8, 10.7, 5)
    NN, DD = np.meshgrid(n_grid, d_grid)
    N, D = NN.ravel(), DD.ravel()

    # Planted surface, written out longhand rather than via skaling_loss.
    L = (A * N ** (-alpha) + B * D ** (-beta)) ** k + E

    params, sse, _success = fit_skaling(N, D, L, n_restarts=60)
    assert params is not None

    pred = skaling_loss(N, D, *params)
    assert sse < 1e-12, f"sse = {sse:.3e}"
    assert np.allclose(pred, L, rtol=1e-8, atol=1e-10)

    # The identified parameters themselves, not just the surface.
    got = dict(zip(["A", "alpha", "B", "beta", "k", "E"], params))
    assert got["A"] == pytest.approx(A, rel=1e-3)
    assert got["alpha"] == pytest.approx(alpha, rel=1e-3)
    assert got["B"] == pytest.approx(B, rel=1e-3)
    assert got["beta"] == pytest.approx(beta, rel=1e-3)
    assert got["k"] == pytest.approx(k, rel=1e-3)
    assert got["E"] == pytest.approx(E, rel=1e-3)


def test_skaling_family_attains_every_chinchilla_fit():
    """Whatever Chinchilla fits, Skaling's family reproduces at k = 1.

    This is the nesting claim at the level of the model rather than the
    optimiser: Chinchilla's own fitted parameters, re-read as Skaling
    parameters with k = 1, give the same SSE on the same data. (Whether the
    6-parameter search FINDS that point on real data is a separate, optimiser
    question - it is what the five-law comparison run measures, not something
    a test can assert.)
    """
    from scaling_laws.laws import fit_chinchilla

    E, A, alpha, B, beta = 1.5, 3.0e3, 0.32, 5.0e4, 0.28
    n_grid = np.logspace(7, 9, 5)
    d_grid = np.logspace(8, 10.7, 5)
    NN, DD = np.meshgrid(n_grid, d_grid)
    N, D = NN.ravel(), DD.ravel()
    L = E + A / N ** alpha + B / D ** beta

    p_ch, sse_ch, _ = fit_chinchilla(N, D, L, n_restarts=60)
    assert p_ch is not None
    E_f, A_f, alpha_f, B_f, beta_f = p_ch

    pred_sk = skaling_loss(N, D, A_f, alpha_f, B_f, beta_f, 1.0, E_f)
    pred_ch = chinchilla_loss(N, D, E_f, A_f, alpha_f, B_f, beta_f)
    np.testing.assert_allclose(pred_sk, pred_ch, rtol=np.finfo(float).eps, atol=0.0)

    # The SSE agrees to the precision the prediction agreement allows. Both fits
    # here are essentially exact (SSE ~1e-19), so a one-ulp difference per
    # prediction is a large RELATIVE difference in a near-zero SSE - hence a
    # tolerance on the SSE loose where the predictions are tight.
    sse_as_skaling = float(np.sum((pred_sk - L) ** 2))
    assert sse_as_skaling == pytest.approx(sse_ch, rel=1e-2, abs=1e-24)


