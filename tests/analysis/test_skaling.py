def test_fit_skaling_reaches_above_the_old_k_ceiling():
    """k = 2.5 lies above the old bound of 2.0; the widened bound must let the fit reach it."""
    A, alpha, B, beta, k, E = 5.0e2, 0.30, 4.0e3, 0.25, 2.5, 1.0
    n_grid = np.logspace(7, 9, 5)
    d_grid = np.logspace(8, 10.7, 5)
    NN, DD = np.meshgrid(n_grid, d_grid)
    N, D = NN.ravel(), DD.ravel()
    L = (A * N ** (-alpha) + B * D ** (-beta)) ** k + E

    params, sse, _ = fit_skaling(N, D, L, n_restarts=60)
    assert params is not None and sse < 1e-10, sse
    assert params[4] == pytest.approx(k, rel=1e-3)


def test_skaling_is_an_extra_law():
    by_name = {law.name: law for law in EXTRA_LAWS}
    assert "Skaling" in by_name, f"extra laws: {sorted(by_name)}"
    law = by_name["Skaling"]
    assert law.loss_fn is skaling_loss
    assert law.fit_fn is fit_skaling
    assert len(law.param_names) == 6
    assert not law.is_epoch_law


def test_paper_laws_are_unchanged():
    assert [law.name for law in LAWS] == ["Kaplan", "Chinchilla", "Droppo-Elibol",
                                          "Parametric-Epoch"]
    import run_analysis

    assert "Skaling" not in run_analysis.LAWS
