#!/usr/bin/env python3
"""Write the bodies of the appendix's two Amendment-5 tables, so no cell is typed by hand.

Reads amendment5_1b.csv (amendments/amendment5_1b.py; default the committed one in
``results/``). Percent is rounded to an integer, or to one decimal where the integer would
hide the sign. Writes ``public_checkpoints_1b.tex`` (the estimators) and
``public_checkpoints_windows.tex`` (the window constructions) into ``--out-dir`` (default
``tables/`` in the work directory).

    uv run python tables/tables_a5_tex.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # the reanalysis modules
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "amendments"))
from amendment5_1b import CONSTRUCTIONS
from paths import RESULTS, WORK
from tables_tex import HEADER

HEAD = "% Generated by tables_a5_tex.py from amendment5_1b.csv; do not edit by hand.\n"
PRE = "pre-registered (W1, window cluster)"
CENTROID = "A5.4c smooth linear, at the >=1B centroid"
ROWS = [  # (printed name, spec, arm); None is a rule
    ("Pre-registered (Table~\\ref{tab:public_checkpoints_results})", PRE, "NC"),
    ("Moving-block interval, $L = 4$", "A5.3 W1, moving block L=4", "NC"),
    ("Clusters of cell, window and ray", "A5.4b (cell, window, ray) cluster", "NC"),
    ("Pairs resampled (anti-conservative)", "A5.4a pair cluster (anti-conservative)", "NC"),
    ("Fixed effect per window", "companion: fixed effect per window", "NC"),
    ("Second subset", PRE, "NCM"),
    ("Second subset, clusters of cell, window and ray", "A5.4b (cell, window, ray) cluster", "NCM"),
    None,
    ("Smooth in $\\log N$, at the band's centroid", CENTROID, "NC"),
    ("Same, quadratic in $\\log N$", "A5.4c smooth quadratic, at the >=1B centroid", "NC"),
    ("Smooth in $\\log N$, at $N = 1$B", "A5.4c smooth linear, at log10 N = 9.0", "NC"),
    ("Smooth in $\\log N$, at $N = 3.2$B", "A5.4c smooth linear, at log10 N = 9.5", "NC"),
    ("Smooth in $\\log N$, at $N = 10$B", "A5.4c smooth linear, at log10 N = 10.0", "NC"),
    ("Second subset, smooth, at the centroid", CENTROID, "NCM"),
]


def p(x: float) -> str:
    v = int(round(float(x)))
    return f"{float(x):.1f}\\%" if v == 0 and abs(float(x)) >= 0.05 else f"{v}\\%"


def both(x: str) -> str:
    return "\\multicolumn{2}{c}{" + x + "}"


class A5:
    """Lookup of the rows of amendment5_1b.csv."""

    def __init__(self, a5: pd.DataFrame) -> None:
        self.a5 = a5

    def row(self, corpus: str, spec: str, arm: str = "NC") -> pd.Series | None:
        q = self.a5[(self.a5.corpus == corpus) & (self.a5.spec == spec) & (self.a5.arm == arm)]
        return None if q.empty else q.iloc[0]

    def cell(self, corpus: str, spec: str, arm: str) -> str:
        r = self.row(corpus, spec, arm)
        return both("-") if r is None else f"${p(r.pct)}$ & $[{p(r.pct_lo)}, {p(r.pct_hi)}]$"


def estimators_table(a: A5) -> str:
    lines = list(HEADER)
    for r in ROWS:
        if r is None:
            lines.append(r"\midrule")
            continue
        name, spec, arm = r
        lines.append(f"{name} & {a.cell('E', spec, arm)} & {a.cell('X', spec, arm)} \\\\")
    lines.append(r"\midrule")
    for name, spec in (("One-sided 95\\% lower bound", PRE),
                       ("Same, smooth in $\\log N$", CENTROID)):
        e, x = (a.row(c, spec) for c in ("E", "X"))
        lines.append(f"{name} & {both('$' + p(e.pct_one_sided_lo) + '$')} & "
                     f"{both('$' + p(x.pct_one_sided_lo) + '$')} \\\\")
    for name, spec in (("Attenuation bound, share of the effect below 1B",
                        "A5.4d attenuation fraction, unpooled"),
                       ("Same, smooth in $\\log N$", "A5.4d attenuation fraction, smooth")):
        e = a.row("E", spec)
        lines.append(f"{name} & {both('$' + p(100 * e.pct_one_sided_lo) + '$')} & "
                     f"{both('-')} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return HEAD + "\n".join(lines) + "\n"


def windows_table(a: A5) -> str:
    lines = [r"\begin{tabular}{@{}rrrrll@{}}", r"\toprule",
             r"Width & Stride & Windows & Estimate & Window interval & Moving-block interval \\",
             r"\midrule"]
    for name, (w, s) in CONSTRUCTIONS.items():
        L = int(np.ceil(w / s))
        r = a.row("E", f"A5.3 {name} ({w},{s}), 128 seeds, window cluster")
        b = a.row("E", f"A5.3 {name} ({w},{s}), 128 seeds, moving block L={L}")
        mb = "same" if L == 1 else f"$[{p(b.pct_lo)}, {p(b.pct_hi)}]$ ($L = {L}$)"
        lines.append(f"{w} & {s} & {int(r.n_windows)} & ${p(r.pct)}$ & "
                     f"$[{p(r.pct_lo)}, {p(r.pct_hi)}]$ & {mb} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return HEAD + "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--amendment5", default=str(RESULTS / "amendment5_1b.csv"))
    ap.add_argument("--out-dir", default=str(WORK / "tables"))
    args = ap.parse_args(argv)
    a = A5(pd.read_csv(args.amendment5))
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name, text in (("public_checkpoints_1b.tex", estimators_table(a)),
                       ("public_checkpoints_windows.tex", windows_table(a))):
        (out / name).write_text(text)
        print(text)


if __name__ == "__main__":
    main()
