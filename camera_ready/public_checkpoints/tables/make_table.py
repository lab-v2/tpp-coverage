#!/usr/bin/env python3
"""Write the body of the appendix's study table from per_study.csv, so no cell is typed by hand.

Every source a row's data came through is cited: the Chinchilla points are Besiroglu et
al.'s digitization, and five releases come through ColPret (Choshen et al.): Chinchilla,
Gadre et al., MAD, GPT-3 and OPT, whose losses ColPret takes from Xia et al.

Reads ``per_study.csv`` (per_study.py; default the committed ``results/per_study.csv``) and
writes ``public_checkpoints_studies.tex`` into ``--out-dir`` (default ``tables/`` in the work
directory).

    uv run python tables/make_table.py
"""

from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # the reanalysis modules
from paths import RESULTS, WORK

CITE = {"Farseer": "li2025farseer",
        "Chinchilla isoFLOP": "hoffmann2022training,besiroglu2024chinchilla,choshen2024hitchhiker",
        "Gemstones annealed": "mcleish2025gemstonesmodelsuitemultifaceted",
        "Gadre et al.": "gadre2024language,choshen2024hitchhiker",
        "OLMo ladder": "bhagia2025establishingtaskscalinglaws",
        "DataDecide": "magnusson2025datadecidepredictbestpretraining",
        "MAD": "poli2024mechanistic,choshen2024hitchhiker",
        "Gemstones constant LR": "mcleish2025gemstonesmodelsuitemultifaceted",
        "GPT-3 curves": "brown2020language,choshen2024hitchhiker",
        "OPT trajectories": "zhang2022opt,xia2023training,choshen2024hitchhiker"}
# Printed names; "Gadre et al. over-training" would print the name twice next to its citation.
NAME = {"Gadre et al.": "Over-training suite"}


def sig(x: str) -> str:
    """Two significant digits below 10, an integer above."""
    v = float(x)
    return f"{v:.2g}" if math.floor(math.log10(v)) < 0 or v < 10 else f"{v:.0f}"


def size(n: str) -> str:
    v = float(n)
    return f"{v / 1e9:.3g}B" if v >= 1e9 else f"{v / 1e6:.3g}M"


def table(rows: list[dict]) -> str:
    out = ["% Generated by make_table.py from per_study.csv; do not edit by hand.",
           r"\begin{tabular}{@{}p{0.42\linewidth}lrrll@{}}", r"\toprule",
           r"Study & Losses & Points & Sizes & $N$ range & TPP range \\", r"\midrule"]
    for r in rows:
        kind = "final" if r["corpus"] == "E" else "trajectory"
        name = NAME.get(r["study"], r["study"])
        pts = f"{int(r['runs_used']):,}".replace(",", "{,}")
        # The Study column wraps (a p column, ragged right) so the rows citing two sources fit.
        out.append(f"\\raggedright {name}~\\citep{{{CITE[r['study']]}}} & {kind} & {pts} & "
                   f"{r['distinct_N_union']} & {size(r['N_min'])}--{size(r['N_max'])} & "
                   f"{sig(r['TPP_min'])}--{sig(r['TPP_max'])} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--per-study", default=str(RESULTS / "per_study.csv"))
    ap.add_argument("--out-dir", default=str(WORK / "tables"))
    args = ap.parse_args(argv)
    with open(args.per_study, newline="") as fh:
        rows = list(csv.DictReader(fh))
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "public_checkpoints_studies.tex").write_text(table(rows))
    print(table(rows))


if __name__ == "__main__":
    main()
