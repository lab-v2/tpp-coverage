#!/usr/bin/env python3
"""Write the bodies of the appendix's estimate and regime tables, so no cell is typed by hand.

The estimate table (margin regression): rows of estimates_seeds512.csv (estimate.py),
percent 10 ** beta - 1 rounded to an integer; the five releases' band below 100M is printed
as not established (CRITERIA A6.2e).
The regime table: replicate 0 of regime_cells.csv (intervals/regime_cells.py, family
``joint``): NC win rate to 0.1%, median gap and its 200,000-draw window-cluster interval to 3
decimals, or to as many as it takes for a nonzero value to show its sign.

Reads the two CSVs (default the committed ones in ``results/``) and writes
``public_checkpoints_results.tex`` and ``public_checkpoints_regimes.tex`` into ``--out-dir``
(default ``tables/`` in the work directory).

    uv run python tables/tables_tex.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # the reanalysis modules
from paths import RESULTS, WORK

HEAD = "% Generated by tables_tex.py from {src}; do not edit by hand.\n"
HEADER = [r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
          r" & \multicolumn{2}{c}{Five fully trained} & \multicolumn{2}{c}{All ten} \\",
          r"\cmidrule(lr){2-3}\cmidrule(l){4-5}",
          r"Specification & Estimate & 95\% interval & Estimate & 95\% interval \\", r"\midrule"]
ESTIMATE_ROWS = [  # (printed name, section, spec, arm); None is a rule
    ("Within a cell (primary)", "1 primary", "cell FE (PRIMARY)", "NC"),
    ("Pooled, no fixed effect", "1 primary", "no fixed effect (pooled)", "NC"),
    ("Pooled, suite-weighted", "1 primary", "no FE, suite-weighted (A4.4)", "NC"),
    ("Within a cell, suite-weighted", "1 primary", "cell FE, suite-weighted (A4.4)", "NC"),
    ("Fixed effect per window", "1 primary", "(cell,window) FE", "NC"),
    ("Complete cases", "1 primary", "cell FE, complete case", "NC"),
    ("Chinchilla law only", "1 primary", "law = Chinchilla", "NC"),
    ("Kaplan law only", "1 primary", "law = Kaplan", "NC"),
    (r"$\beta_{\mathrm{eff}} = 0.10$", "1 primary", "C2 beta_eff = 0.1", "NC"),
    (r"$\beta_{\mathrm{eff}} = 0.50$", "1 primary", "C2 beta_eff = 0.5", "NC"),
    ("Second subset, within a cell", "1 primary", "NCM arm, cell FE", "NCM"),
    ("Second subset, fixed effect per window", "1 primary", "NCM arm, (cell,window) FE", "NCM"),
    ("Second subset, no fixed effect", "1 primary", "NCM arm, no fixed effect", "NCM"),
    None,
    ("Windows centred below 100M", "3 stratum", "stratum <100M", "NC"),
    ("Windows centred at 100M to 1B", "3 stratum", "stratum 100M-1B", "NC"),
    ("Windows centred at 1B and above", "3 stratum", "stratum >=1B", "NC"),
    None,
    (r"Size interaction, per tenfold $N$", "3 interaction", "b1 Delta x logN", "NC"),
]
KAPPAS = (1e2, 1e4, 1e5, 1e6)
CELLS = ("CO=A,NC=B", "CO=A,NC=A", "CO=B,NC=B", "CO=B,NC=A")


def p(x: float) -> str:
    return f"{int(round(float(x)))}\\%"


def estimate_table(est: pd.DataFrame) -> str:
    lines = list(HEADER)
    for row in ESTIMATE_ROWS:
        if row is None:
            lines.append(r"\midrule")
            continue
        name, sec, spec, arm = row
        q = est[(est.section == sec) & (est.spec == spec) & (est.arm == arm)].set_index("corpus")
        cell = [f"${p(r.pct_512)}$ & $[{p(r.pct_lo_512)}, {p(r.pct_hi_512)}]$"
                for r in (q.loc["E"], q.loc["X"])]
        if spec == "stratum <100M":
            cell[0] = r"\multicolumn{2}{c}{not established (2 windows, 1 cell)}"
        lines.append(f"{name} & {cell[0]} & {cell[1]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return HEAD.format(src="estimates_seeds512.csv") + "\n".join(lines) + "\n"


def g(x: float) -> str:
    """Three decimals, or as many (up to six) as a nonzero value needs to show its sign."""
    for d in range(3, 7):
        s = f"{x:.{d}f}"
        if float(s) != 0.0 or x == 0.0:
            return s
    return s


def regime_table(cells: pd.DataFrame) -> str:
    j = cells[cells.family == "joint"].set_index(["corpus", "kappa", "cell"])
    lines = [r"\begin{tabular}{@{}rccrlrl@{}}", r"\toprule",
             r" & & & \multicolumn{2}{c}{Five fully trained} & \multicolumn{2}{c}{All ten} \\",
             r"\cmidrule(lr){4-5}\cmidrule(l){6-7}",
             r"$\kappa_{\mathrm{target}}$ & CO & NC & NC wins & Median $g$ & NC wins & Median $g$ \\",
             r"\midrule"]
    for kappa in KAPPAS:
        for cell in CELLS:
            rs = [j.loc[(c, kappa, cell)] for c in ("E", "X")]
            if all(r.n_pairs == 0 for r in rs):
                continue
            out = [r"\multicolumn{2}{c}{no pairs}" if r.n_pairs == 0 else
                   f"${100 * r.win:.1f}\\%$ & ${g(r['median'])}$ $[{g(r.lo)}, {g(r.hi)}]$"
                   for r in rs]
            lines.append(f"$10^{int(np.log10(kappa))}$ & {cell[3]} & {cell[-1]} & "
                         f"{out[0]} & {out[1]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return HEAD.format(src="regime_cells.csv (replicate 0, 200,000 draws)") + "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--estimates", default=str(RESULTS / "estimates_seeds512.csv"))
    ap.add_argument("--regime-cells", default=str(RESULTS / "regime_cells.csv"))
    ap.add_argument("--out-dir", default=str(WORK / "tables"))
    args = ap.parse_args(argv)
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name, text in (("public_checkpoints_results.tex",
                        estimate_table(pd.read_csv(args.estimates))),
                       ("public_checkpoints_regimes.tex",
                        regime_table(pd.read_csv(args.regime_cells)))):
        (out / name).write_text(text)
        print(text)


if __name__ == "__main__":
    main()
